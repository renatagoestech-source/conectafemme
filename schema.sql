-- ConectaFemme: PostgreSQL / Supabase
-- A aplicação acessa os dados apenas pela Edge Function de servidor.
CREATE TABLE IF NOT EXISTS public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role text NOT NULL CHECK (role IN ('admin','provider','client')),
  name varchar(120) NOT NULL,
  email varchar(160) NOT NULL UNIQUE,
  pass varchar(255) NOT NULL,
  whatsapp varchar(30) NOT NULL DEFAULT '',
  state varchar(2) NOT NULL DEFAULT '',
  city varchar(80) NOT NULL DEFAULT '',
  created timestamptz NOT NULL DEFAULT now(),
  is_demo boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public.categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.providers (
  user_id bigint PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
  category varchar(80),
  specialties text[] NOT NULL DEFAULT '{}'::text[] CHECK (cardinality(specialties) <= 2),
  bio text NOT NULL DEFAULT '',
  logo varchar(500) NOT NULL DEFAULT '',
  cover_image varchar(500) NOT NULL DEFAULT '',
  state varchar(2) NOT NULL DEFAULT '',
  city varchar(80) NOT NULL DEFAULT '',
  instagram_url varchar(255) NOT NULL DEFAULT '',
  weekly_schedule jsonb NOT NULL DEFAULT '{}'::jsonb,
  is_founder boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public.services (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id bigint NOT NULL REFERENCES public.providers(user_id) ON DELETE CASCADE,
  title varchar(160) NOT NULL,
  descr text NOT NULL DEFAULT '',
  price numeric(10,2) NOT NULL CHECK (price >= 0),
  images text NOT NULL DEFAULT '[]'
);

CREATE TABLE IF NOT EXISTS public.slots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id bigint NOT NULL REFERENCES public.providers(user_id) ON DELETE CASCADE,
  day date NOT NULL,
  hour varchar(5) NOT NULL,
  booked boolean NOT NULL DEFAULT false,
  available boolean NOT NULL DEFAULT true,
  schedule_managed boolean NOT NULL DEFAULT false,
  CONSTRAINT slots_provider_day_hour_unique UNIQUE(provider_id, day, hour)
);

CREATE TABLE IF NOT EXISTS public.bookings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slot_id bigint NOT NULL REFERENCES public.slots(id) ON DELETE CASCADE,
  service_id bigint NOT NULL REFERENCES public.services(id) ON DELETE CASCADE,
  client_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
  provider_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  manual_client_name varchar(120) NOT NULL DEFAULT '',
  manual_client_whatsapp varchar(30) NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente','confirmado','concluido','cancelado')),
  created timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.provider_payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  client_name varchar(120) NOT NULL DEFAULT '',
  service_title varchar(160) NOT NULL DEFAULT '',
  amount numeric(12,2) NOT NULL CHECK (amount > 0),
  payment_method text NOT NULL CHECK (payment_method IN ('pix','dinheiro','credito','debito','transferencia','outro')),
  paid_on date NOT NULL DEFAULT CURRENT_DATE,
  note varchar(500) NOT NULL DEFAULT '',
  created timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL UNIQUE REFERENCES public.bookings(id) ON DELETE CASCADE,
  client_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  provider_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment varchar(500) NOT NULL DEFAULT '',
  created timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS providers_category_idx ON public.providers(category);
CREATE INDEX IF NOT EXISTS services_provider_idx ON public.services(provider_id);
CREATE INDEX IF NOT EXISTS slots_provider_day_idx ON public.slots(provider_id, day);
CREATE INDEX IF NOT EXISTS bookings_client_idx ON public.bookings(client_id, created DESC);
CREATE INDEX IF NOT EXISTS bookings_provider_idx ON public.bookings(provider_id, created DESC);
CREATE INDEX IF NOT EXISTS reviews_provider_idx ON public.reviews(provider_id, created DESC);
CREATE INDEX IF NOT EXISTS reviews_client_idx ON public.reviews(client_id, created DESC);
CREATE INDEX IF NOT EXISTS provider_payments_provider_date_idx ON public.provider_payments(provider_id, paid_on DESC, created DESC);
CREATE INDEX IF NOT EXISTS users_demo_idx ON public.users(is_demo, role) WHERE is_demo = true;

