-- Canal de suporte para profissionais: chamados, protocolo sequencial e conversa privada.
CREATE SEQUENCE IF NOT EXISTS public.support_ticket_protocol_seq;

CREATE TABLE IF NOT EXISTS public.support_tickets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocol varchar(32) NOT NULL UNIQUE DEFAULT (
    'CF-' || to_char(timezone('America/Sao_Paulo', now()), 'YYYY') || '-' ||
    lpad(nextval('public.support_ticket_protocol_seq')::text, 6, '0')
  ),
  professional_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  admin_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  subject varchar(150) NOT NULL,
  status text NOT NULL DEFAULT 'aberto' CHECK (status IN ('aberto', 'resolvido')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.support_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id bigint NOT NULL REFERENCES public.support_tickets(id) ON DELETE CASCADE,
  sender_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  recipient_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  body text NOT NULL CHECK (length(btrim(body)) BETWEEN 1 AND 5000),
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz
);

CREATE INDEX IF NOT EXISTS support_tickets_professional_updated_idx
  ON public.support_tickets (professional_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS support_tickets_admin_updated_idx
  ON public.support_tickets (admin_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS support_messages_ticket_created_idx
  ON public.support_messages (ticket_id, created_at ASC);
CREATE INDEX IF NOT EXISTS support_messages_recipient_unread_idx
  ON public.support_messages (recipient_id, created_at DESC) WHERE read_at IS NULL;

ALTER TABLE public.support_tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_messages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.support_tickets FROM anon, authenticated;
REVOKE ALL ON TABLE public.support_messages FROM anon, authenticated;
GRANT ALL ON TABLE public.support_tickets TO service_role;
GRANT ALL ON TABLE public.support_messages TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.support_ticket_protocol_seq TO service_role;
