-- Lançamentos financeiros privados para controle interno de cada profissional.
CREATE TABLE IF NOT EXISTS public.provider_payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id bigint NOT NULL REFERENCES public.providers(user_id) ON DELETE CASCADE,
  paid_on date NOT NULL DEFAULT CURRENT_DATE,
  client_name varchar(120) NOT NULL DEFAULT '',
  description varchar(200) NOT NULL DEFAULT '',
  amount numeric(10,2) NOT NULL CHECK (amount > 0 AND amount <= 99999999.99),
  method varchar(24) NOT NULL CHECK (method IN ('pix','dinheiro','cartao_credito','cartao_debito','transferencia','outro')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS provider_payments_provider_date_idx
  ON public.provider_payments(provider_id, paid_on DESC, created_at DESC);

ALTER TABLE public.provider_payments ENABLE ROW LEVEL SECURITY;
